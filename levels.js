function buildZombieMap() {
  const Wd = 33, Hd = 29; const g = []; for (let r = 0; r < Hd; r++) g.push(new Array(Wd).fill('"'));
  const put = (c, r, ch) => { if (g[r] && c >= 0 && c < Wd) g[r][c] = ch; };
  // дорога
  for (let r = 17; r < Hd; r++) { put(16, r, '_'); put(15, r, '_'); put(17, r, '_'); }
  for (let c = 0; c < Wd; c++) { put(c, 25, '_'); put(c, 24, '_'); }
  // дом 11x9 в центре: cols 11..21, rows 8..16
  const hx = 11, hy = 8, hw = 11, hh = 9;
  for (let r = 0; r < hh; r++) for (let c = 0; c < hw; c++) put(hx + c, hy + r, (r === 0 || r === hh - 1 || c === 0 || c === hw - 1) ? '#' : ',');
  put(16, 8, ','); put(15, 8, ','); put(16, 16, ','); put(17, 16, ','); put(11, 12, ','); put(21, 12, ','); // двери
  put(16, 12, 'G'); put(13, 10, 'S'); put(14, 10, '+'); put(19, 14, 'D'); put(20, 14, '+'); put(20, 9, 'L'); put(12, 15, 'A');
  put(15, 13, 'P'); put(17, 13, 'P'); put(13, 13, 'c'); put(19, 11, 'c'); put(14, 14, 'c'); put(18, 9, 'c');
  // заборы, ёлки, тачка
  for (let c = 6; c <= 9; c++) put(c, 5, 'F'); for (let c = 23; c <= 26; c++) put(c, 5, 'F');
  for (let r = 10; r <= 13; r++) { put(6, r, 'f'); put(26, r, 'f'); }
  for (let c = 6; c <= 9; c++) put(c, 20, 'F'); for (let c = 23; c <= 26; c++) put(c, 20, 'F');
  for (const [c, r] of [[3, 3], [9, 2], [14, 3], [20, 2], [27, 3], [30, 7], [2, 9], [29, 13], [3, 16], [30, 19], [4, 22], [10, 22], [22, 22], [28, 22], [8, 14], [24, 15], [12, 27], [21, 27], [2, 27], [30, 27], [9, 8], [24, 8]]) put(c, r, 'N');
  put(19, 22, 'C'); put(20, 22, '+'); put(21, 22, '+');
  // спавны зомби по краям
  for (const [c, r] of [[0, 0], [8, 0], [16, 0], [24, 0], [32, 0], [0, 7], [32, 7], [0, 14], [32, 14], [0, 21], [32, 21], [0, 28], [8, 28], [16, 28], [24, 28], [32, 28]]) put(c, r, 'z');
  return g.map(r => r.join(''));
}
